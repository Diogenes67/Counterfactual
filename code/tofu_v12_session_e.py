import numpy as np
from scipy import stats as _st

def deltas(r):
    b = r["forget_logprob"]
    q = r["quant"]
    return {"benign_ft": max(r["relearn_benign"]) - b,      # Table row: Benign fine-tuning
            "relearn5":  max(r["savings"]) - b,             # Table row: Relearning (five forget examples)
            "quant4":    (q.get("4") or q.get(4))["forget_logprob"] - b}  # Table row: 4-bit quantisation

def block(title, paths, expect=None):
    print(f"\n--- {title} ---")
    per = {}
    for p in sorted(paths):
        r = json.load(open(p))
        d = deltas(r)
        per.setdefault("tags", []).append(r["tag"])
        for k, v in d.items():
            per.setdefault(k, []).append(v)
        print(" ", r["tag"], " ".join(f"{k} {v:+.2f}" for k, v in d.items()))
    for k in ["benign_ft", "relearn5", "quant4"]:
        v = per.get(k, [])
        if len(v) >= 2:
            m, sd = np.mean(v), np.std(v, ddof=1)
            half = _st.t.ppf(0.975, len(v)-1) * _st.sem(v)
            t, p = _st.ttest_1samp(v, 0.0, alternative="greater")
            print(f"  {k}: mean {m:+.2f} +/- {sd:.2f} s.d. (95% CI +/-{half:.2f}, "
                  f"n={len(v)}, one-sided P={p:.3g})")
        elif len(v) == 1:
            print(f"  {k}: single value {v[0]:+.2f} (n=1)")
    if expect:
        print("  expected (published 1.5B):", expect)
    return per

